/**
 * The capability gateway core — Kotlin sibling of hosts/ios Gateway/-
 * GatewayCore.swift. Dispatch table name→handler, permission enforcement
 * against the caller's bundle manifest (data-protocols.md §2), and the
 * mandatory structured audit of contract/primitives.md §6 — one record per
 * call, never payload contents. Audit rides its own logcat tag
 * ("dsh.runtime.audit") with the flat "dsh.gateway.audit: " prefix so the
 * canonical "dsh.runtime.log: " E2E stream stays one-to-one. Handlers run on
 * the dispatching (runtime) thread and call done OFF it — every settle hop
 * back via JsRuntime.post (ARCHITECTURE.md §6 thread rules).
 */
/** One descriptor row's per-entry self-description (the descriptor-plane
 * grammar — the shape GatewayCore.PRIMITIVE_FACTS maps names to; the values
 * are generator-owned, the shape lives here). */
data class PrimitiveFact(
    val schemaVersion: Int,
    val auditClass: String,
    val permissionFlag: String?,
)

/** One declared row's self-description object; a row the registry does not
 * know fails loud (rule 5) — add it to the registry, then re-emit. */
private fun entryJson(name: String): JSONObject {
    val fact = GatewayCore.PRIMITIVE_FACTS[name]
        ?: error("descriptor row $name has no capability-registry fact — run tools/check-descriptor-parity.mjs --emit")
    return JSONObject()
        .put("name", name)
        .put("schemaVersion", fact.schemaVersion)
        .put("auditClass", fact.auditClass)
        .put("permissionFlag", fact.permissionFlag ?: JSONObject.NULL)
}

